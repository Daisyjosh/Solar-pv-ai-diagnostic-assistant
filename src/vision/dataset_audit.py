"""Dataset inventory, quality auditing, near-duplicate screening, and provenance classification.

Engineering Principles:
- Scans actual directories recursively and reports verifiable file counts without extrapolation.
- Distinguishes synthetic/verification fixtures from operational inspection uploads and external benchmarks.
- Screens for exact duplicates (SHA-256) and flags candidate near-duplicates via configurable perceptual hashing (aHash).
- Identifies corrupt files, zero-byte artifacts, and missing metadata.
- Avoids exposing sensitive GPS coordinates in public audit reports.
- Generates reproducible machine-readable JSON and human-readable Markdown reports.
"""

import hashlib
import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

import numpy as np
from PIL import Image

from src.vision.metadata import extract_image_metadata
from src.vision.preprocessing import RadiometricStatus, ThermalPreprocessor


class ProvenanceType(str, Enum):
    """Categorization of image origin and operational validity."""

    SYNTHETIC_VERIFICATION_FIXTURE = "SYNTHETIC_VERIFICATION_FIXTURE"
    OPERATIONAL_INSPECTION_UPLOAD = "OPERATIONAL_INSPECTION_UPLOAD"
    EXTERNAL_BENCHMARK_DATASET = "EXTERNAL_BENCHMARK_DATASET"
    UNKNOWN_PROVENANCE = "UNKNOWN_PROVENANCE"


@dataclass
class ImageAuditRecord:
    """Individual image file audit record."""

    relative_path: str
    file_size_bytes: int
    format: str
    width: int
    height: int
    channels: int
    provenance: ProvenanceType
    sha256: str
    ahash: str
    is_corrupt: bool = False
    corruption_error: Optional[str] = None
    has_exif: bool = False
    has_gps: bool = False
    camera_make: Optional[str] = None
    camera_model: Optional[str] = None
    radiometric_status: str = RadiometricStatus.NOT_CONFIRMED.value


@dataclass
class AuditSummary:
    """Aggregated dataset quality and inventory metrics."""

    scan_timestamp_utc: str
    scanned_directory: str
    total_files_scanned: int = 0
    valid_images_count: int = 0
    corrupt_files_count: int = 0
    zero_byte_files_count: int = 0
    format_distribution: Dict[str, int] = field(default_factory=dict)
    provenance_distribution: Dict[str, int] = field(default_factory=dict)
    radiometric_distribution: Dict[str, int] = field(default_factory=dict)
    exact_duplicates_count: int = 0
    exact_duplicate_groups: List[List[str]] = field(default_factory=list)
    near_duplicate_candidate_pairs: List[Dict[str, Any]] = field(default_factory=list)
    files_with_gps: int = 0
    files_with_camera_metadata: int = 0
    license_documentation: str = "Unknown / Not documented in scanned directory"
    records: List[ImageAuditRecord] = field(default_factory=list)


def compute_average_hash(pil_img: Image.Image, hash_size: int = 8) -> str:
    """Compute 64-bit Average Hash (aHash) for near-duplicate candidate screening."""
    try:
        # Resize to 8x8 grayscale
        resized = pil_img.convert("L").resize((hash_size, hash_size), Image.Resampling.LANCZOS)
        pixels = np.array(resized)
        avg = pixels.mean()
        # Compute boolean bitstring
        bits = pixels > avg
        hex_str = "".join(f"{byte:02x}" for byte in np.packbits(bits))
        return hex_str
    except Exception:
        return "0" * 16


def hamming_distance(hex1: str, hex2: str) -> int:
    """Compute bitwise Hamming distance between two hexadecimal hash strings."""
    try:
        val1 = int(hex1, 16)
        val2 = int(hex2, 16)
        return bin(val1 ^ val2).count("1")
    except Exception:
        return 64


class DatasetAuditor:
    """Performs empirical inventory and quality audit across dataset directories."""

    SUPPORTED_EXTENSIONS: Set[str] = {".jpg", ".jpeg", ".png", ".tif", ".tiff"}

    def __init__(self, near_dup_hamming_threshold: int = 4):
        """Initialize auditor.

        Args:
            near_dup_hamming_threshold: Maximum Hamming distance to flag candidate near-duplicates.
        """
        self.near_dup_threshold = near_dup_hamming_threshold
        self.thermal_preprocessor = ThermalPreprocessor()

    def _determine_provenance(self, file_path: Path) -> ProvenanceType:
        """Classify image origin based on verified path and naming provenance."""
        path_str = file_path.as_posix().lower()
        name = file_path.name.lower()

        # Known verification fixture names generated by integration tests
        fixture_tokens = ("vue_capture", "ortho_rgb", "rendered_ironbow", "plain_optical", "thermal_flir")
        if any(tok in name for tok in fixture_tokens):
            return ProvenanceType.SYNTHETIC_VERIFICATION_FIXTURE

        if "tests" in path_str:
            return ProvenanceType.SYNTHETIC_VERIFICATION_FIXTURE

        if "data/raw/inspections" in path_str:
            return ProvenanceType.OPERATIONAL_INSPECTION_UPLOAD

        if "data/external" in path_str:
            return ProvenanceType.EXTERNAL_BENCHMARK_DATASET

        return ProvenanceType.UNKNOWN_PROVENANCE

    def audit_directory(self, target_dir: Path) -> AuditSummary:
        """Audit target directory recursively."""
        target_dir = Path(target_dir).resolve()
        summary = AuditSummary(
            scan_timestamp_utc=datetime.now(timezone.utc).isoformat(),
            scanned_directory=str(target_dir),
        )

        if not target_dir.exists():
            return summary

        # 1. Check for license files
        for lic_candidate in ("LICENSE", "LICENSE.txt", "README.md", "README.txt"):
            lic_path = target_dir / lic_candidate
            if lic_path.is_file():
                summary.license_documentation = f"Refer to {lic_candidate}"
                break

        sha_map: Dict[str, List[str]] = {}
        valid_records: List[ImageAuditRecord] = []

        # 2. Walk directory
        for p in sorted(target_dir.rglob("*")):
            if not p.is_file():
                continue

            summary.total_files_scanned += 1
            ext = p.suffix.lower()

            if ext not in self.SUPPORTED_EXTENSIONS:
                continue

            file_size = p.stat().st_size
            rel_path = p.relative_to(target_dir).as_posix()

            # Check zero-byte file
            if file_size == 0:
                summary.zero_byte_files_count += 1
                summary.corrupt_files_count += 1
                continue

            # Compute SHA-256
            hasher = hashlib.sha256()
            try:
                hasher.update(p.read_bytes())
                sha256_hex = hasher.hexdigest()
            except Exception as exc:
                summary.corrupt_files_count += 1
                continue

            # Track exact duplicates
            sha_map.setdefault(sha256_hex, []).append(rel_path)

            # Inspect image decode
            try:
                with Image.open(p) as img:
                    img_fmt = (img.format or "").upper()
                    w, h = img.width, img.height
                    channels = len(img.getbands())
                    ahash = compute_average_hash(img)

                meta = extract_image_metadata(p)
                rad_status, _, _ = self.thermal_preprocessor.identify_modality(p)
                provenance = self._determine_provenance(p)

                rec = ImageAuditRecord(
                    relative_path=rel_path,
                    file_size_bytes=file_size,
                    format=img_fmt,
                    width=w,
                    height=h,
                    channels=channels,
                    provenance=provenance,
                    sha256=sha256_hex,
                    ahash=ahash,
                    is_corrupt=False,
                    has_exif=(meta.camera_make is not None or meta.captured_at is not None),
                    has_gps=(meta.gps_latitude is not None and meta.gps_longitude is not None),
                    camera_make=meta.camera_make,
                    camera_model=meta.camera_model,
                    radiometric_status=rad_status.value,
                )

                summary.valid_images_count += 1
                summary.format_distribution[img_fmt] = summary.format_distribution.get(img_fmt, 0) + 1
                summary.provenance_distribution[provenance.value] = (
                    summary.provenance_distribution.get(provenance.value, 0) + 1
                )
                summary.radiometric_distribution[rad_status.value] = (
                    summary.radiometric_distribution.get(rad_status.value, 0) + 1
                )

                if rec.has_gps:
                    summary.files_with_gps += 1
                if rec.camera_make:
                    summary.files_with_camera_metadata += 1

                valid_records.append(rec)

            except Exception as exc:
                summary.corrupt_files_count += 1
                rec = ImageAuditRecord(
                    relative_path=rel_path,
                    file_size_bytes=file_size,
                    format=ext.replace(".", "").upper(),
                    width=0,
                    height=0,
                    channels=0,
                    provenance=self._determine_provenance(p),
                    sha256=sha256_hex,
                    ahash="0" * 16,
                    is_corrupt=True,
                    corruption_error=str(exc),
                )
                valid_records.append(rec)

        summary.records = valid_records

        # 3. Identify exact duplicates
        for sha, files in sha_map.items():
            if len(files) > 1:
                summary.exact_duplicates_count += len(files) - 1
                summary.exact_duplicate_groups.append(files)

        # 4. Identify candidate near-duplicates (pairwise aHash Hamming distance)
        candidates = []
        for i in range(len(valid_records)):
            for j in range(i + 1, len(valid_records)):
                rec1, rec2 = valid_records[i], valid_records[j]
                if rec1.sha256 == rec2.sha256:
                    continue  # Already captured as exact duplicate
                dist = hamming_distance(rec1.ahash, rec2.ahash)
                if dist <= self.near_dup_threshold:
                    candidates.append({
                        "file_a": rec1.relative_path,
                        "file_b": rec2.relative_path,
                        "hamming_distance": dist,
                        "threshold": self.near_dup_threshold,
                        "note": "Candidate near-duplicate flagged for review; does not prove scene identity",
                    })

        summary.near_duplicate_candidate_pairs = candidates
        return summary

    def generate_markdown_report(self, summary: AuditSummary) -> str:
        """Render audit summary into formal Markdown."""
        lines = [
            "# Solar PV AI Diagnostic Assistant — Dataset Inventory & Quality Audit",
            "",
            f"**Audit Timestamp (UTC):** `{summary.scan_timestamp_utc}`  ",
            f"**Scanned Directory:** `{summary.scanned_directory}`  ",
            f"**License Documentation:** {summary.license_documentation}",
            "",
            "---",
            "",
            "## 1. Inventory Summary",
            "",
            f"- **Total Files Scanned:** {summary.total_files_scanned}",
            f"- **Valid Images Ingested:** {summary.valid_images_count}",
            f"- **Corrupt Files:** {summary.corrupt_files_count}",
            f"- **Zero-Byte Files:** {summary.zero_byte_files_count}",
            f"- **Exact Duplicates (SHA-256):** {summary.exact_duplicates_count}",
            f"- **Candidate Near-Duplicates (aHash ≤ {self.near_dup_threshold}):** {len(summary.near_duplicate_candidate_pairs)}",
            "",
            "### Format Distribution",
            "| Format | Count |",
            "|:---|:---:|",
        ]
        for fmt, cnt in summary.format_distribution.items():
            lines.append(f"| {fmt} | {cnt} |")
        if not summary.format_distribution:
            lines.append("| *None* | 0 |")

        lines.extend([
            "",
            "### Provenance & Operational Validity",
            "> [!NOTE]",
            "> Synthetic fixtures generated by integration tests are strictly distinguished from operational plant imagery.",
            "> They MUST NOT be cited as evidence of real-world AI diagnostic accuracy.",
            "",
            "| Provenance Category | Count | Description |",
            "|:---|:---:|:---|",
        ])
        for prov, cnt in summary.provenance_distribution.items():
            desc = "Operational inspection capture" if "OPERATIONAL" in prov else "Integration test fixture"
            lines.append(f"| `{prov}` | {cnt} | {desc} |")
        if not summary.provenance_distribution:
            lines.append("| *None* | 0 | No image files detected |")

        lines.extend([
            "",
            "### Radiometric Data Integrity",
            "> [!IMPORTANT]",
            "> 8-bit rendered false-color images (e.g. Ironbow/Rainbow palettes) do not contain raw sensor measurements.",
            "> Emissivity and temperature are recorded ONLY when genuine radiometric metadata is verified.",
            "",
            "| Radiometric Classification | Count |",
            "|:---|:---:|",
        ])
        for rad, cnt in summary.radiometric_distribution.items():
            lines.append(f"| `{rad}` | {cnt} |")
        if not summary.radiometric_distribution:
            lines.append("| *None* | 0 |")

        lines.extend([
            "",
            "## 2. Duplicate Analysis",
            "",
        ])
        if summary.exact_duplicate_groups:
            lines.append("### Exact Duplicate Groups (Identical SHA-256)")
            for grp in summary.exact_duplicate_groups:
                lines.append(f"- Group: `{', '.join(grp)}`")
        else:
            lines.append("No exact duplicates detected.")

        lines.append("")
        if summary.near_duplicate_candidate_pairs:
            lines.append(f"### Candidate Near-Duplicates (Hamming Distance ≤ {self.near_dup_threshold})")
            lines.append("> [!TIP]")
            lines.append("> Perceptual hashing flags candidates for review; it does not constitute mathematical proof of scene duplication.")
            for pair in summary.near_duplicate_candidate_pairs:
                lines.append(f"- `{pair['file_a']}` ↔ `{pair['file_b']}` (Hamming Distance: {pair['hamming_distance']})")
        else:
            lines.append("No candidate near-duplicates detected.")

        lines.extend([
            "",
            "## 3. Detailed File Roster",
            "",
            "| File Path | Format | Dimensions | Channels | Radiometric Status | Provenance |",
            "|:---|:---:|:---:|:---:|:---:|:---|",
        ])
        for r in summary.records:
            status_flag = "⚠️ Corrupt" if r.is_corrupt else r.radiometric_status
            lines.append(
                f"| `{r.relative_path}` | {r.format} | {r.width}x{r.height} | {r.channels} | {status_flag} | `{r.provenance.value}` |"
            )
        if not summary.records:
            lines.append("| *No image files present* | - | - | - | - | - |")

        return "\n".join(lines)
